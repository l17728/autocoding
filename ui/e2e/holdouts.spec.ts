import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('isolated evaluation intake freezes scene before immutable answer',async({page})=>{
  await page.goto('/');
  await page.getByLabel('访问令牌',{exact:true}).fill(readFileSync('../.local/ui-e2e/.local/workbench/owner-token.txt','utf8'));
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByText('知识效果对照评测',{exact:true}).click();
  await page.getByText('隔离采集新的评测场景',{exact:true}).click();
  await page.getByLabel('样本来源与背景').fill('独立采集页面测试');
  const marker='holdout-scene-'+Date.now();
  await page.getByLabel('新评测场景',{exact:true}).fill(marker);
  await page.getByLabel('场景范围',{exact:true}).selectOption('outside');
  await page.getByRole('button',{name:'登记场景并冻结基线',exact:true}).click();
  const sample=page.locator('article').filter({has:page.getByText(marker,{exact:true})});
  await expect(sample).toContainText('待填写标准答案');
  await sample.getByLabel('标准答案 JSON').fill('{"choice":"verify"}');
  await sample.getByRole('button',{name:'保存标准答案（不可覆盖）',exact:true}).click();
  await expect(sample).toContainText('待独立性复核');
  await expect(sample.getByLabel('标准答案 JSON')).toHaveCount(0);
  await expect(sample).toContainText('verify');
  await page.getByRole('button',{name:'查看隔离样本',exact:true}).click();
  await expect(sample).toContainText('待独立性复核');
  await sample.getByLabel('复核依据').fill('已核查独立来源、背景、答案和语义重叠。');
  await sample.getByRole('button',{name:'复核通过',exact:true}).click();
  await expect(sample).toContainText('Owner 复核通过');
  await sample.getByLabel('选择导出样本').check();
  await page.getByLabel('样本来源与背景').fill('新的范围内场景');
  await page.getByLabel('新评测场景',{exact:true}).fill(marker+'-inside');
  await page.getByLabel('场景范围',{exact:true}).selectOption('inside');
  await page.getByRole('button',{name:'登记场景并冻结基线',exact:true}).click();
  const second=page.locator('article').filter({has:page.getByText(marker+'-inside',{exact:true})});
  await second.getByLabel('标准答案 JSON').fill('{"choice":"verify"}');
  await second.getByRole('button',{name:'保存标准答案（不可覆盖）',exact:true}).click();
  await second.getByLabel('复核依据').fill('已核查独立来源和语义重叠，答案与场景一致。');
  await second.getByRole('button',{name:'复核通过',exact:true}).click();
  await second.getByLabel('选择导出样本').check();
  await page.getByRole('button',{name:'生成版本化导出（须含范围外反例）',exact:true}).click();
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载评测清单 JSON',exact:true}).click();
  expect((await downloadEvent).suggestedFilename()).toMatch(/^holdout_export_.*\.json$/);
  await page.getByRole('button',{name:'接入成对评测集（替换当前集，不调用模型）',exact:true}).click();
  await page.getByRole('button',{name:'载入评测',exact:true}).click();
  await expect(page.getByText('当前使用经 Owner 复核的隔离样本',{exact:false})).toBeVisible();
  await sample.getByRole('button',{name:'标记污染（不可恢复）',exact:true}).click();
  await expect(sample).toContainText('已污染（不可恢复）');
  await expect(sample.getByRole('button',{name:'复核通过',exact:true})).toHaveCount(0);
});
