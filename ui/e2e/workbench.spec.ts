test('real browser terminal authenticates, echoes unicode, resizes and closes',async({page})=>{
  test.setTimeout(90000);
  let output='',resizes=0,keys=0,terminalChunks=0;
  page.on('websocket',socket=>socket.on('framereceived',event=>{
    const message=JSON.parse(String(event.payload));
    output+=(message.frames||[]).map((frame:{text:string})=>frame.text).join('');
  }));
  page.on('request',request=>{if(request.url().endsWith('/resize'))resizes++});
  page.on('request',request=>{if(request.url().endsWith('/key'))keys++});
  page.on('request',request=>{if(/TerminalPanel-.*\.js/.test(request.url()))terminalChunks++});
  await page.goto('/');
  await page.getByLabel('访问令牌',{exact:true}).fill(readFileSync('../.local/ui-e2e/.local/workbench/owner-token.txt','utf-8'));
  await page.getByRole('button',{name:'进入工作台'}).click();
  await expect(page.getByRole('button',{name:'打开本机终端',exact:true})).toBeVisible();
  expect(terminalChunks).toBe(0);
  await page.getByRole('button',{name:'打开本机终端',exact:true}).click();
  await page.getByRole('button',{name:'启动终端',exact:true}).click();
  expect(terminalChunks).toBeGreaterThan(0);
  await expect.poll(()=>output,{timeout:30000}).toContain('TERMINAL_READY');
  await page.getByLabel('终端输入',{exact:true}).fill('浏览器中文回显');
  await page.getByRole('button',{name:'发送到终端',exact:true}).click();
  await expect.poll(()=>output,{timeout:15000}).toContain('ECHO:浏览器中文回显');
  // PTY output may arrive before the HTTP write receipt and session refresh.
  await expect(page.getByRole('button',{name:'接管终端',exact:true})).toBeEnabled();
  await page.getByTestId('terminal-screen').locator('.xterm-helper-textarea').focus();
  await page.keyboard.type('keyboardz');
  await page.keyboard.press('Backspace');
  await page.keyboard.press('Enter');
  await expect.poll(()=>output,{timeout:15000}).toContain('ECHO:keyboard');
  const beforeComposition=keys;
  await page.getByTestId('terminal-screen').locator('.xterm-helper-textarea').evaluate(element=>{
    element.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',code:'Enter',isComposing:true,bubbles:true,cancelable:true}));
  });
  await page.waitForTimeout(250);
  expect(keys).toBe(beforeComposition);
  const previous=resizes;
  await page.setViewportSize({width:1100,height:850});
  await expect.poll(()=>resizes).toBeGreaterThan(previous);
  const beforeReconnect=(output.match(/TERMINAL_READY/g)||[]).length;
  await page.getByRole('button',{name:'重新连接输出',exact:true}).click();
  await expect.poll(()=>(output.match(/TERMINAL_READY/g)||[]).length).toBeGreaterThan(beforeReconnect);
  await page.getByTestId('terminal-screen').scrollIntoViewIfNeeded();
  await page.screenshot({path:'../.local/browser-terminal.png',fullPage:true});
  await page.getByRole('button',{name:'关闭终端',exact:true}).click();
  await expect(page.getByRole('button',{name:'发送到终端',exact:true})).toBeDisabled();
  const previousReady=(output.match(/TERMINAL_READY/g)||[]).length;
  await page.getByRole('button',{name:'恢复终端',exact:true}).click();
  await expect.poll(()=>(output.match(/TERMINAL_READY/g)||[]).length,{timeout:30000}).toBeGreaterThan(previousReady);
  await page.getByTestId('terminal-screen').locator('.xterm-helper-textarea').focus();
  await page.keyboard.press('Control+c');
  await expect(page.getByRole('button',{name:'发送到终端',exact:true})).toBeDisabled();
});
